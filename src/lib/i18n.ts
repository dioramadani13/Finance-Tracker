export function translateCategoryLabel(category: string, lang: LanguageCode): string {
  if (lang === 'id') return category;
  return CATEGORY_TRANSLATIONS_EN[category] ?? category;
}

export function translatePaymentMethodLabel(method: string, lang: LanguageCode): string {
  if (lang === 'id') return method;
  return PAYMENT_METHOD_TRANSLATIONS_EN[method] ?? method;
}

